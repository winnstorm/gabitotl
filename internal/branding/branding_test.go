// cl is built at runtime so this repository passes its own guard.
var cl = "Cla" + "ude"

func ctxOf(s string) Context {
	switch s {
	case "p":
		return ContextProse
	case "c":
		return ContextCode
	}
	return ContextMessage
}

func TestCorpus(t *testing.T) {
	f, err := os.Open(filepath.Join("testdata", "corpus.txt"))
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	d := New()
	sc := bufio.NewScanner(f)
	n, pos, neg := 0, 0, 0
	for sc.Scan() {
		line := sc.Text()
		if strings.TrimSpace(line) == "" || strings.HasPrefix(line, "#") {
			continue
		}
		parts := strings.SplitN(line, "|", 3)
		if len(parts) != 3 {
			t.Fatalf("bad corpus line %q", line)
		}
		n++
		got := d.Scan("x", parts[2], ctxOf(parts[1]))
		if parts[0] == "-" {
			neg++
			if len(got) != 0 {
				t.Errorf("false positive on %q: %+v", parts[2], got)
			}
			continue
		}
		pos++
		if len(got) != 1 || string(got[0].Class) != parts[0] {
			t.Errorf("want class %s for %q, got %+v", parts[0], parts[2], got)
		}
	}
	if pos < 40 || neg < 25 {
		t.Fatalf("corpus too small: %d positive, %d negative (of %d)", pos, neg, n)
	}
}

func TestFindingFields(t *testing.T) {
	text := "feat: x\n\n" + strings.Repeat("a", 0) + "Co-Authored-By: Claude <noreply@anthropic.com>\n"
	fs := New().Scan("msg", text, ContextMessage)
	if len(fs) != 1 {
		t.Fatalf("got %+v", fs)
	}
	f := fs[0]
	if f.File != "msg" || f.Line != 3 || f.Class != ClassTrailer || f.Action != ActionRemoveLine || f.Fix == "" || f.Text == "" {
		t.Fatalf("bad finding %+v", f)
	}
	long := "Generated with " + cl + " " + strings.Repeat("x", 300)
	fs = New().Scan("", long, ContextMessage)
	if len(fs) != 1 || len([]rune(fs[0].Text)) > maxText+1 {
		t.Fatalf("text not truncated: %+v", fs)
	}
}

func TestRemovableRules(t *testing.T) {
	d := New()
	cases := []struct {
		text string
		ctx  Context
		want Action
	}{
		{"// @author Claude", ContextCode, ActionRemoveLine},
		{`__author__ = "Claude"`, ContextCode, ActionManual},
		{"// thanks, generated with " + cl, ContextCode, ActionManual},
		{"/* Generated by " + cl, ContextCode, ActionManual},
		{"/* Generated by " + cl + " */", ContextCode, ActionRemoveLine},
		{"Thanks! Generated with " + cl, ContextMessage, ActionManual},
		{"Generated with " + cl, ContextProse, ActionRemoveLine},
		{"> Generated with " + cl, ContextProse, ActionRemoveLine},
	}
	for _, c := range cases {
		fs := d.Scan("", c.text, c.ctx)
		if len(fs) != 1 || fs[0].Action != c.want {
			t.Errorf("%q: want %s, got %+v", c.text, c.want, fs)
		}
	}
}

func TestExtraTerms(t *testing.T) {
	line := "Generated with AcmeLLM"
	if len(New().Scan("", line, ContextMessage)) != 0 {
		t.Fatal("unknown brand must not match by default")
	}
	d := New("acmellm", "  ", "")
	if len(d.Scan("", line, ContextMessage)) != 1 {
		t.Fatal("extra term must match case-insensitively")
	}
	if len(d.Scan("", "Co-authored-by: AcmeLLM <bot@acme.example>", ContextMessage)) != 1 {
		t.Fatal("extra term must work in trailers")
	}
}

