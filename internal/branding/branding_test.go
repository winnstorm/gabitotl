func TestStrip(t *testing.T) {
	msg := "feat(x): add thing\n\nBody line.\n\n🤖 " + "Generated with [" + cl + " Code](https://claude.com/" + "claude-code)\n\nCo-Authored-By: " + cl + " <noreply@anthropic.com>\n"
	clean, removed, remaining := New().Strip(msg)
	if clean != "feat(x): add thing\n\nBody line." {
		t.Fatalf("clean = %q", clean)
	}
	if len(removed) != 2 || len(remaining) != 0 {
		t.Fatalf("removed=%+v remaining=%+v", removed, remaining)
	}
	same, r, _ := New().Strip("feat: nothing to do\n")
	if same != "feat: nothing to do\n" || len(r) != 0 {
		t.Fatalf("untouched text must be returned as is: %q", same)
	}
	_, r, rem := New().Strip("feat: x\n\nThanks, generated with " + cl)
	if len(r) != 0 || len(rem) != 1 {
		t.Fatalf("shared line must stay and be reported: %+v %+v", r, rem)
	}
}

func TestSkippedAndAllowed(t *testing.T) {
	for _, p := range []string{".git/config", ".git", ".gabitotl/.bak/u/x.md", "sub/.git/HEAD"} {
		if !Skipped(p) {
			t.Errorf("%s must be skipped", p)
		}
	}
	for _, p := range []string{".gabitotl/workflow.md", "src/git.go", ".github/x.yml"} {
		if Skipped(p) {
			t.Errorf("%s must not be skipped", p)
		}
	}
	globs := []string{"docs/runtimes/**", "internal/*/testdata/", "*.snap", "README.md"}
	for p, want := range map[string]bool{
		"docs/runtimes/a/b.md":         true,
		"docs/other.md":                false,
		"internal/branding/testdata/x": true,
		"internal/a/b/testdata/x":      false,
		"x/y/z.snap":                   true,
		"README.md":                    true,
		"sub/README.md":                true,
	} {
		if got := Allowed(p, globs); got != want {
			t.Errorf("Allowed(%s) = %v, want %v", p, got, want)
		}
	}
}

func TestScanPaths(t *testing.T) {
	root := t.TempDir()
	write := func(rel, body string) {
		p := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	bad := "Generated with " + cl + "\n"
	write("a.md", bad)
	write("allowed/b.md", bad)
	write(".git/c.md", bad)
	write(".gabitotl/.bak/u/d.md", bad)
	write("bin.dat", "\x00\x01"+bad)
	write("ok.md", "Supports Claude Code.\n")
	rels := []string{"a.md", "allowed/b.md", ".git/c.md", ".gabitotl/.bak/u/d.md", "bin.dat", "ok.md", "missing.md"}
	got := New().ScanPaths(root, rels, []string{"allowed/"})
	if len(got) != 1 || got[0].File != "a.md" || got[0].Line != 1 {
		t.Fatalf("got %+v", got)
	}
	walked, err := WalkFiles(root)
	if err != nil {
		t.Fatal(err)
	}
	for _, w := range walked {
		if Skipped(w) {
			t.Errorf("walk returned skipped path %s", w)
		}
	}
}

func TestDeterministic(t *testing.T) {
	text := "Generated with " + cl + "\nCo-authored-by: Qwen\nfine\n"
	a := New().Scan("f", text, ContextProse)
	b := New().Scan("f", text, ContextProse)
	if len(a) != 2 || len(a) != len(b) || a[0] != b[0] || a[1] != b[1] {
		t.Fatalf("not deterministic: %+v %+v", a, b)
	}
}
